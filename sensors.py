"""
Фиксированная амплитудная характеристика датчиков ДТ100А1 / ДТ500А1.

Вход — ток (номинал зависит от модели), выход — напряжение, линейно:
    I = 0        -> V = 6 В
    I = +I_ном    -> V = 10 В
    I = -I_ном    -> V = 2 В

Наклон характеристики одинаков для обеих сторон (AMPLITUDE / I_ном),
поэтому одна формула покрывает обе ветви (forward/reverse), если ток уже
подставлен со знаком (см. measurement.py).

Погрешность считается со знаком (важно направление отклонения) и
нормируется по ГОСТ 8.401-80: для средств измерений/преобразователей со
смещённым нулём (выходная шкала не проходит через физический ноль — это
ровно наш случай, выход 2..10 В никогда не равен 0) нормирующее значение
берётся как разность верхнего и нижнего пределов шкалы, а не как значение
"от нуля". Здесь это V_PLUS - V_MINUS = 8 В.
"""
from dataclasses import dataclass

SENSOR_MODELS = {
    "ДТ100А1": 100.0,
    "ДТ500А1": 500.0,
}

# ASCII-псевдонимы для CLI (--model), чтобы не полагаться на ввод кириллицы
# в аргументах командной строки/bat-скриптах.
MODEL_CLI_ALIASES = {
    "DT100A1": "ДТ100А1",
    "DT500A1": "ДТ500А1",
}

V_ZERO = 6.0    # В, выход при I = 0
V_PLUS = 10.0   # В, выход при I = +I_ном
V_MINUS = 2.0   # В, выход при I = -I_ном

AMPLITUDE = V_PLUS - V_ZERO           # 4 В (= V_ZERO - V_MINUS, характеристика симметрична)
SPAN = V_PLUS - V_MINUS               # 8 В — нормирующее значение погрешности (ГОСТ 8.401-80)


@dataclass(frozen=True)
class SensorModel:
    name: str
    i_nom: float


def get_model(name: str) -> SensorModel:
    if name not in SENSOR_MODELS:
        raise ValueError(f"Неизвестная модель датчика: {name!r} (ожидается одна из {list(SENSOR_MODELS)})")
    return SensorModel(name=name, i_nom=SENSOR_MODELS[name])


def expected_voltage(i_set: float, i_nom: float) -> float:
    """Ожидаемое выходное напряжение датчика при токе i_set (со знаком)."""
    return V_ZERO + (AMPLITUDE / i_nom) * i_set


def error_percent(v_meas: float, v_expected: float) -> float:
    """
    Приведённая погрешность со знаком, % от SPAN (8 В).

    Знак сохраняется: положительная погрешность — измеренное напряжение
    выше ожидаемого, отрицательная — ниже. Модуль не берётся умышленно,
    направление отклонения важно для калибровки.
    """
    return (v_meas - v_expected) / SPAN * 100.0
