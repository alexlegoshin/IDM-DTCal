"""
Модели датчиков ДТ100А1 / ДТ500А1.

Здесь остался только справочник моделей: имя -> номинальный ток возбуждения.
Номинал нужен для подстановки диапазона тока в GUI/CLI и для предупреждения
при выходе за него.

Никакой номинальной характеристики «вход -> выход» тут больше нет и быть не
должно. DTCal снимает первичные данные: задали ток — записали напряжение с
датчика. Каким окажется выход (биполярным ±4 В, однополярным 2..10 В или
любым другим), заранее неизвестно и зависит от подключённого датчика.
Погрешность считается вручную по ТЗ/ТУ вне программы.
"""
from dataclasses import dataclass

SENSOR_MODELS = {
    "ДТ100А1": 100.0,
    "ДТ500А1": 500.0,
}

# ASCII-псевдонимы для CLI (--model), чтобы не полагаться на ввод кириллицы
# в аргументах командной строки/bat-скриптах.
MODEL_CLI_ALIASES = {
    "DT100A1": "ДТ100А1",
    "DT500A1": "ДТ500А1",
}


@dataclass(frozen=True)
class SensorModel:
    name: str
    i_nom: float


def get_model(name: str) -> SensorModel:
    if name not in SENSOR_MODELS:
        raise ValueError(f"Неизвестная модель датчика: {name!r} (ожидается одна из {list(SENSOR_MODELS)})")
    return SensorModel(name=name, i_nom=SENSOR_MODELS[name])
